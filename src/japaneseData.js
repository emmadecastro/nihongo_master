// Format compact : une ligne = "caractère|traduction (lecture)"
const build = (prefix, text) =>
  text.trim().split('\n').map((line, i) => {
    const [jp, fr] = line.split('|');
    return { id: `${prefix}-${i + 1}`, jp: jp.trim(), fr: fr.trim() };
  });

const kana = (prefix, chars, romaji) => {
  const c = chars.split(' ');
  const r = romaji.split(' ');
  return c.map((jp, i) => ({ id: `${prefix}${i + 1}`, jp, fr: r[i] }));
};

